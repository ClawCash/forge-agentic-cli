import { looksLikeInstructions } from "./rating.ts"
import { assertPublicHttps } from "./terms.ts"

// How an API describes itself, for its leaderboard card. All of it comes from
// the seller's own site, so it is capped, screened and only ever served as data.

const PAGE_BYTES = 300_000
const ICON_BYTES = 64_000
const TIMEOUT_MS = 4000
const MAX_REDIRECTS = 3
const MAX_ICON_TRIES = 3
const MAX_NAME = 60
const MAX_DESCRIPTION = 180

const BOILERPLATE =
  /^(create next app|generated by create next app|vite \+ react|react app|untitled|home|index|document|welcome.*|not found|404.*|just a moment.*|access denied|attention required.*)$/i
const UNSAFE_SVG = /<script|<foreignobject|<iframe|\son[a-z]+\s*=|javascript:/i
const PNG = Buffer.from("89504e470d0a1a0a", "hex")
const ICO = Buffer.from([0, 0, 1, 0])

export interface Profile {
  name: string | null
  description: string | null
  iconType: string | null
  iconData: string | null
  siteUrl: string | null
}

export type ReadProfile = (domain: string) => Promise<Profile>

function clean(text: string | undefined | null, max: number) {
  if (!text) return null
  const plain = text
    .replace(/[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]/gu, " ")
    .replace(/\s+/g, " ")
    .trim()
  if (!plain || BOILERPLATE.test(plain) || looksLikeInstructions(plain)) {
    return null
  }
  if (plain.length <= max) return plain
  return `${plain.slice(0, max).replace(/\s+\S*$/, "")}…`
}

function decode(text: string) {
  const named: Record<string, string> = {
    amp: "&",
    lt: "<",
    gt: ">",
    quot: '"',
    apos: "'",
    nbsp: " ",
    mdash: "—",
    ndash: "–",
  }
  return text.replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (whole, code: string) => {
    if (!code.startsWith("#")) return named[code.toLowerCase()] ?? whole
    const point = /^#x/i.test(code)
      ? Number.parseInt(code.slice(2), 16)
      : Number.parseInt(code.slice(1), 10)
    return point > 0 && point <= 0x10ffff ? String.fromCodePoint(point) : whole
  })
}

function attributes(tag: string) {
  const found: Record<string, string> = {}
  const pairs = tag.matchAll(/([a-z:-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/gi)
  for (const [, name, double, single] of pairs) {
    found[name.toLowerCase()] = decode(double ?? single ?? "")
  }
  return found
}

function parsePage(html: string, base: string) {
  const meta: Record<string, string> = {}
  for (const [tag] of html.matchAll(/<meta\b[^>]*>/gi)) {
    const { property, name, content } = attributes(tag)
    const key = (property ?? name)?.toLowerCase()
    if (key && content && !(key in meta)) meta[key] = content
  }
  const title = /<title[^>]*>([^<]*)<\/title>/i.exec(html)?.[1]
  const icons = [...html.matchAll(/<link\b[^>]*>/gi)]
    .map(([tag]) => attributes(tag))
    .filter((link) => link.href && /\bicon\b/i.test(link.rel ?? ""))
    .map((link) => ({
      href: link.href,
      rank: /svg/i.test(link.type ?? link.href)
        ? 1000
        : Number(/(\d+)x\d+/.exec(link.sizes ?? "")?.[1]) ||
          (/apple/i.test(link.rel) ? 180 : 16),
    }))
    .sort((a, b) => b.rank - a.rank)
    .flatMap(({ href }) => {
      try {
        const url = new URL(href, base)
        return url.protocol === "https:" ? [url.href] : []
      } catch {
        return []
      }
    })
  return {
    names: [
      meta["og:site_name"],
      title && decode(title).split(/\s+[|–—·:-]\s+/)[0],
    ],
    descriptions: [
      meta["og:description"],
      meta.description,
      meta["twitter:description"],
    ],
    icons,
  }
}

// Decided from the bytes, so a seller's content type counts for nothing.
function imageType(bytes: Buffer) {
  const start = (n: number) => bytes.subarray(0, n)
  if (start(8).equals(PNG)) return "image/png"
  if (bytes[0] === 0xff && bytes[1] === 0xd8) return "image/jpeg"
  if (start(4).toString("latin1") === "GIF8") return "image/gif"
  if (
    start(4).toString("latin1") === "RIFF" &&
    bytes.subarray(8, 12).toString("latin1") === "WEBP"
  ) {
    return "image/webp"
  }
  if (start(4).equals(ICO)) return "image/x-icon"
  const text = bytes.toString("utf8")
  return /^\s*(<\?xml|<!--|<svg\b)/i.test(text) &&
    /<svg\b/i.test(text) &&
    !UNSAFE_SVG.test(text)
    ? "image/svg+xml"
    : null
}

export function profileReader(
  fetchImpl: typeof fetch = fetch,
  assertPublic: (url: string) => Promise<void> = assertPublicHttps
): ReadProfile {
  // Every hop is checked, so a redirect can't reach an internal address.
  async function get(start: string, accept: string, max: number) {
    let url = start
    for (let hop = 0; hop <= MAX_REDIRECTS; hop += 1) {
      await assertPublic(url)
      const res = await fetchImpl(url, {
        redirect: "manual",
        signal: AbortSignal.timeout(TIMEOUT_MS),
        headers: { Accept: accept, "User-Agent": "AgentReviews/1.0" },
      })
      const location = res.headers.get("location")
      if (res.status >= 300 && res.status < 400 && location) {
        await res.body?.cancel()
        url = new URL(location, url).href
        continue
      }
      if (!res.ok || !res.body) {
        await res.body?.cancel()
        return null
      }
      const chunks: Uint8Array[] = []
      let size = 0
      const reader = res.body.getReader()
      while (size <= max) {
        const { done, value } = await reader.read()
        if (done) break
        chunks.push(value)
        size += value.length
      }
      await reader.cancel()
      return {
        url,
        type: res.headers.get("content-type") ?? "",
        body: Buffer.concat(chunks),
      }
    }
    return null
  }

  const quietly = (url: string, accept: string, max: number) =>
    get(url, accept, max).catch(() => null)

  async function readIcon(candidates: string[]) {
    for (const url of candidates.slice(0, MAX_ICON_TRIES)) {
      const icon = await quietly(url, "image/*", ICON_BYTES)
      if (!icon || icon.body.length > ICON_BYTES) continue
      const iconType = imageType(icon.body)
      if (iconType) return { iconType, iconData: icon.body.toString("base64") }
    }
    return { iconType: null, iconData: null }
  }

  return async (domain) => {
    const page =
      (await quietly(`https://${domain}/`, "text/html", PAGE_BYTES)) ??
      (await quietly(`https://www.${domain}/`, "text/html", PAGE_BYTES))
    const origin = page ? new URL(page.url).origin : `https://${domain}`
    const parsed =
      page && /html/i.test(page.type)
        ? parsePage(page.body.toString("utf8"), page.url)
        : { names: [], descriptions: [], icons: [] }

    const pick = (values: (string | undefined)[], max: number) =>
      values.map((value) => clean(value, max)).find(Boolean) ?? null
    let name = pick(parsed.names, MAX_NAME)
    let description = pick(parsed.descriptions, MAX_DESCRIPTION)

    if (!name || !description) {
      const spec = await quietly(
        `${origin}/openapi.json`,
        "application/json",
        PAGE_BYTES
      )
      let info: { title?: unknown; description?: unknown } = {}
      try {
        info = spec ? (JSON.parse(spec.body.toString("utf8")).info ?? {}) : {}
      } catch {
        // Not a usable spec: the card goes without.
      }
      const asText = (value: unknown) =>
        typeof value === "string" ? value : undefined
      name ??= clean(asText(info.title), MAX_NAME)
      description ??= clean(asText(info.description), MAX_DESCRIPTION)
    }

    return {
      name,
      description,
      siteUrl: page ? origin : null,
      ...(await readIcon([...parsed.icons, `${origin}/favicon.ico`])),
    }
  }
}
